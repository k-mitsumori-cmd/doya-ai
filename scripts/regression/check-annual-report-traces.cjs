const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { createRequire } = require('node:module');
const root = process.cwd();
const requireProject = createRequire(path.join(root, 'package.json'));
const traceFile = path.join(root, '.next/server/app/api/annual-report/image/route.js.nft.json');
assert(fs.existsSync(traceFile), 'Build the annual image route before checking its deployment trace');
const trace = JSON.parse(fs.readFileSync(traceFile, 'utf8'));
assert(Array.isArray(trace.files), 'Next trace must contain its file inventory');
const actualPaths = new Set(trace.files.map(file => path.resolve(path.dirname(traceFile), file)).filter(file => fs.existsSync(file)).map(file => fs.realpathSync(file)));
const entry = fs.realpathSync(requireProject.resolve('@resvg/resvg-js'));
assert(actualPaths.has(entry), 'Annual report deployment trace misses the Resvg JavaScript module');
assert.equal(typeof requireProject('@resvg/resvg-js').Resvg, 'function', 'Installed native renderer must load');
const scope = path.dirname(path.dirname(requireProject.resolve('@resvg/resvg-js/package.json')));
const nativeBindings = Object.keys(require.cache).filter(file => file.startsWith(scope + path.sep) && file.endsWith('.node'));
assert(nativeBindings.length > 0, 'Expected the actual host native binding to load');
for (const binding of nativeBindings) assert(actualPaths.has(fs.realpathSync(binding)), 'Annual report deployment trace misses the loaded native binding: ' + path.basename(binding));
console.log(JSON.stringify({ passed: true, platform: process.platform, arch: process.arch, nativeBindings: nativeBindings.map(file => path.relative(root, file)), scope: 'Actual built annual image route trace contains both the renderer entry and the native binding loaded on this host. Runtime image rendering and other deployment platforms are separate checks.' }));
