// ガードレールの検証。誤検知（正当な質問を弾く）と見逃しの両方を見る。
// 実行: npx tsx scripts/guardrail_check.ts
import { findViolations } from '../src/lib/mensetsu/guardrails'

const MUST_BLOCK = [
  'ご家族は何をされていますか', 'ご両親はご健在ですか', 'お父様のご職業を教えてください',
  'お母様は働いていらっしゃいますか', '母親はどちらにお勤めですか', 'ご家族構成を教えてください',
  '同居されているご家族はいますか', '扶養家族は何人ですか', 'ご結婚のご予定はありますか',
  '結婚はされていますか', '既婚ですか未婚ですか', 'ご婚約されていますか',
  '妊娠されていますか', '産休を取得される予定はありますか', '育休の予定はありますか',
  'お子さんはいらっしゃいますか', '子どもは何人いますか', '出産のご予定はありますか',
  '本籍はどちらですか', '出身地はどちらですか', 'ご家庭の状況を教えてください',
  '持ち家ですか借家ですか', '宗教は何を信仰していますか', '支持政党はありますか',
  '尊敬する人物は誰ですか', '愛読書を教えてください', '労働組合に入っていましたか',
  '国籍を教えてください', '何歳ですか', '持病はありますか',
  '性的指向について教えてください', 'ご両親の学歴を教えてください',
]

const MUST_ALLOW = [
  // 業務・職務に関する正当な質問。ここが弾かれると業種ごとテンプレートを保存できない
  '結婚式場での接客経験を教えてください', 'ブライダル業界での実績を教えてください',
  '産休・育休の制度設計を担当されたことはありますか', '育休制度の運用で工夫した点は何ですか',
  '分母は何を取って算出しましたか', '母国語以外に話せる言語はありますか',
  '母校での学びを業務にどう活かしましたか', '母集団形成の施策を教えてください',
  '子ども向け商材の企画経験を教えてください', '子ども服のEC運営で工夫した点は',
  '出産祝いギフトの販促を担当された経験は', 'ご家族向けサービスの設計経験は',
  'チームで意見が割れたときどう合意形成しましたか', '直近の担当業務を教えてください',
  '難しかった案件と、その進め方を教えてください', '売上に対する貢献を具体的に教えてください',
  '兄弟会社との連携経験はありますか',
]

let ng = 0
for (const t of MUST_BLOCK) {
  const v = findViolations([t])
  if (v.length === 0) { console.log(`  見逃し: ${t}`); ng++ }
}
for (const t of MUST_ALLOW) {
  const v = findViolations([t])
  if (v.length > 0) { console.log(`  誤検知: ${t}  → ${v[0].label}`); ng++ }
}
console.log(`\nブロック対象 ${MUST_BLOCK.length}件 / 通すべき ${MUST_ALLOW.length}件 → 問題 ${ng}件`)
process.exit(ng > 0 ? 1 : 0)
