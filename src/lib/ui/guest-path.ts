// ============================================
// 第三者が開く画面かどうかの判定
// ============================================
// ⚠️ 応募者・見込み客・まだ組織に入っていない招待者が開く画面には、
//    アプリ枠（サイドバー / ツール切替 / アップグレード案内）を出してはいけない。
//    自社のサービス一覧と料金を、社外の方に見せることになる。
//
// ⚠️ **セッションの有無だけで判定しないこと。**
//    採用担当者が自分でログインしたまま面接URLを開く、
//    招待された方がログイン後に招待受諾画面へ戻る、といった経路があり、
//    どちらも「ログイン済みだが第三者向け画面」になる。
//    （2026-08-18: ServiceTopBar を廃止した際にこの判定が落ち、
//      ログイン済みで /mensetsu/live/[token] を開くと社内一覧が出る状態になっていた）
//
// ⚠️ ゲスト経路を増やしたらここにも追加すること。

const GUEST_PATH_PATTERNS: RegExp[] = [
  // 応募者が開く面接画面
  /^\/mensetsu\/live\//,
  // 招待の受諾画面。どのサービスでも扱いを揃える
  /^\/[a-z]+\/invite\//,
  // 見込み客が開く商談ルーム
  /^\/m\//,
]

export function isGuestPath(pathname: string | null | undefined): boolean {
  const p = pathname || ''
  return GUEST_PATH_PATTERNS.some((re) => re.test(p))
}
