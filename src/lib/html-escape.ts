// ============================================
// HTMLエスケープ（メール本文・生成HTML共通）
// ============================================
// ⚠️ テンプレートリテラルでHTMLを組み立てる箇所では、
//    利用者が入力した値を必ずこれに通すこと。
//
//    招待メールで組織名を素のまま埋め込んでいた実績がある。
//    組織名は誰でも自由に付けられるため、HTMLを仕込んだ名前の組織を作れば
//    招待メールの本文に任意のマークアップを注入できた
//    （偽のリンクや文言を差し込むフィッシングが成立する）。

export function escapeHtml(s: unknown): string {
  return String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
}
