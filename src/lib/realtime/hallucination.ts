// ============================================
// 音声認識のハルシネーション除去（Realtime共通）
// ============================================
// ⚠️ Whisper系のモデルは、**無音や環境雑音に対して文章を捏造する**。
//    学習データ（動画字幕）に由来する定型句が典型で、日本語では
//    「ご視聴ありがとうございました」「チャンネル登録お願いします」が頻出する。
//
//    2026-08-09 の実機テスト（ドヤAI商談）で実際に発生し、
//      - 商談ログに存在しない発言が混入する
//      - AIがそれに反応して「周りが賑やかなようですね」と応じ、ターンを消費する
//      - その結果、同じ確認を3回繰り返して商談が前に進まない
//    という形で表面化した。ログ・評価・スロット抽出のすべてを汚染する。
//
// ⚠️ 雑音由来のランダムな捏造（「現在火星でルンロを追跡中」等）は
//    文面から機械的に判別できない。ここで潰せるのは定型句だけであり、
//    残りは VAD のしきい値とミュート導線で減らす（完全には消えない）。
//
// ⚠️ 誤って本物の発話を捨てると「答えたのに記録されない」という
//    より重い事故になる。パターンは**完全一致に近い形**に留め、
//    部分一致で広く弾かないこと。

/** 無音・雑音に対して繰り返し現れる定型句 */
const HALLUCINATION_PATTERNS: RegExp[] = [
  /^ご(視聴|清聴)(いただき)?ありがとうございました[。!！]?$/,
  /^最後まで(ご視聴|お読み)/,
  /^(高評価と)?チャンネル登録(と高評価)?(を)?(ぜひ)?(よろしく)?お願いします[。!！]?$/,
  /^(ありがとうございました|ありがとうございます)[。!！]?$/,
  /^おやすみなさい[。!！]?$/,
  // ⚠️ 「はい」「うん」等の単独の肯定は**弾かない**。
  //    Whisperの捏造として最も多い語だが、同時に「ご導入いただけますか」への
  //    正当な返答でもある。捨てると本当に答えた同意がログから消え、
  //    「答えたのに記録されない」というより重い事故になる。
  //    （実際に「御社のチャンネル登録者数は…」という正当な質問を
  //      捨ててしまう誤検出も自前のテストで見つかった）
  /^Thank you for watching/i,
  /^Thanks for watching/i,
  /^Please subscribe/i,
  /^\[?(音楽|拍手|BGM|Music|Applause)\]?$/i,
  /^字幕(：|:)/,
]

/**
 * 文字起こし結果を捨てるべきか。
 * @param text 認識されたテキスト
 * @param speaker 話者。AI側は読み上げテキストが正本なので素通しする
 */
export function isLikelyHallucination(
  text: string,
  speaker: 'ai' | 'guest' | 'candidate' | 'interviewer'
): boolean {
  if (speaker === 'ai' || speaker === 'interviewer') return false
  const t = text.trim()
  if (!t) return true
  // 記号や空白を除いて1文字しか残らないものは、意味のある発話とみなさない
  const stripped = t.replace(/[\s。、!！?？.,・ー〜]/g, '')
  if (stripped.length <= 1) return true
  return HALLUCINATION_PATTERNS.some((re) => re.test(t))
}
