const assert = require('node:assert/strict');
module.exports = async ({ page, db, origin, tokens, http, reset, make, open, typeSelf, click, has, pass }) => {
  const role = async (role, employeeId) => db.hrOrganizationMember.update({ where: { id: 'synthetic-member-A' }, data: { role, employeeId } });
  const patches = () => http.filter(x => x.method === 'PATCH').length;
  await page.setCookie({ name: 'next-auth.session-token', value: tokens.A, url: origin, httpOnly: true, sameSite: 'Lax' });
  await reset(); let e = await make(); await role('MEMBER', 'synthetic-target-A');
  await open(page, e); await typeSelf(page, 'Native self workflow draft');
  await click(page, '自己評価を提出する'); const before = patches();
  await click(page, '保存して操作を確定する'); await has(page, '評価を提出しました');
  let row = await db.hrEvaluation.findUnique({ where: { id: e.id } });
  assert.equal(row.status, 'SUBMITTED'); assert.equal(row.selfComment, 'Native self workflow draft'); assert.ok(row.submittedAt);
  assert.equal(patches(), before + 2);
  await page.reload({ waitUntil: 'domcontentloaded' }); await has(page, '提出済み');
  assert.equal(await page.$eval('textarea[placeholder^="この評価期間"]', field => field.disabled), true);
  assert.equal(await page.evaluate(() => Object.keys(localStorage).some(k => k.startsWith('hr-evaluation-save-intent:'))), false);
  pass('Native target submission saves draft then one durable action and stays read only after reload');

  await reset();
  await db.hrEmployee.upsert({ where: { id: 'synthetic-native-evaluator' }, create: { id: 'synthetic-native-evaluator', organizationId: 'synthetic-org-A', firstName: 'Synthetic', lastName: 'Reviewer' }, update: { organizationId: 'synthetic-org-A' } });
  e = await make(); await db.hrEvaluation.update({ where: { id: e.id }, data: { status: 'SUBMITTED', evaluatorId: 'synthetic-native-evaluator' } });
  await role('MANAGER', 'synthetic-native-evaluator'); await open(page, e);
  await page.$eval('textarea[placeholder^="部下への"]', field => { Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype, 'value').set.call(field, 'Native manager reviewed comment'); field.dispatchEvent(new Event('input', { bubbles: true })); });
  await click(page, '上司評価を完了する'); await click(page, '保存して操作を確定する'); await has(page, 'レビューを完了しました');
  row = await db.hrEvaluation.findUnique({ where: { id: e.id } });
  assert.equal(row.status, 'REVIEWED'); assert.ok(row.reviewedAt); assert.equal(row.managerComment, 'Native manager reviewed comment');
  await page.reload({ waitUntil: 'domcontentloaded' }); await has(page, '評価済み');
  assert.equal(await page.$eval('textarea[placeholder^="部下への"]', field => field.disabled), true);
  pass('Native assigned evaluator completes review with persisted timestamp and reload protection');

  await reset(); e = await make(); await role('MEMBER', 'synthetic-target-A'); await open(page, e);
  await typeSelf(page, 'Native lost workflow private draft'); await click(page, '自己評価を提出する');
  await page.evaluate(() => { window.__dropWorkflowAck = true; }); const lostBefore = patches();
  await click(page, '保存して操作を確定する'); await has(page, '保存の応答を確認できませんでした');
  assert.equal((await db.hrEvaluation.findUnique({ where: { id: e.id } })).status, 'SUBMITTED');
  assert.equal(patches(), lostBefore + 2);
  assert.equal(await page.evaluate(() => Object.keys(localStorage).filter(k => k.startsWith('hr-evaluation-save-intent:')).length), 1);
  await page.reload({ waitUntil: 'domcontentloaded' }); await has(page, '前回の保存結果が未確認');
  await click(page, '保存操作の結果を確認する'); await has(page, '前回の保存は完了しています');
  await click(page, '現在の保存内容を確認する'); await click(page, '入力を破棄し、保存内容で開き直す');
  // Confirmation awaits Web Locks before removing the durable intent; a click does not await the React async handler.
  await page.waitForFunction(() => !Object.keys(localStorage).some(k => k.startsWith('hr-evaluation-save-intent:')) && !document.body.textContent.includes('入力を破棄し、保存内容で開き直す'), { timeout: 12000, polling: 100 });
  assert.equal(await page.evaluate(() => Object.keys(localStorage).filter(k => k.startsWith('hr-evaluation-save-intent:')).length), 0);
  assert.equal(patches(), lostBefore + 2);
  assert.equal(await page.$eval('textarea[placeholder^="この評価期間"]', field => field.value), 'Native lost workflow private draft');
  assert.equal(await page.$eval('textarea[placeholder^="この評価期間"]', field => field.disabled), true);
  pass('Native lost self submission ACK survives reload and explicit receipt recovery with no resubmission');

  const reviewer = 'synthetic-native-evaluator';
  await reset(); e = await make(); await open(page, e);
  await page.waitForFunction(id => [...(document.querySelector('#evaluation-evaluator')?.options || [])].some(option => option.value === id), { timeout: 12000 }, reviewer);
  await page.select('#evaluation-evaluator', reviewer); await typeSelf(page, 'Native assignment draft');
  await click(page, '保存する'); await has(page, '評価を保存しました');
  row = await db.hrEvaluation.findUnique({ where: { id: e.id } });
  assert.equal(row.evaluatorId, reviewer); assert.equal(row.selfComment, 'Native assignment draft');
  await role('MEMBER', 'synthetic-target-A'); await open(page, e);
  await click(page, '自己評価を提出する'); await click(page, '保存して操作を確定する'); await has(page, '評価を提出しました');
  await role('MANAGER', reviewer); await open(page, e);
  await click(page, '上司評価を完了する'); await click(page, '保存して操作を確定する'); await has(page, 'レビューを完了しました');
  await role('OWNER', null); await open(page, e);
  await click(page, '評価を確定する'); await click(page, '保存して操作を確定する'); await has(page, '評価を確定しました');
  row = await db.hrEvaluation.findUnique({ where: { id: e.id } });
  assert.equal(row.status, 'FINALIZED'); assert.equal(row.evaluatorId, reviewer); assert.ok(row.submittedAt && row.reviewedAt && row.finalizedAt);
  pass('Native UI assigns an existing evaluation and completes actual self assigned-reviewer admin workflow');

  await reset(); e = await make(); await open(page, e);
  await page.waitForFunction(id => [...(document.querySelector('#evaluation-evaluator')?.options || [])].some(option => option.value === id), { timeout: 12000 }, reviewer);
  await page.select('#evaluation-evaluator', reviewer); await typeSelf(page, 'Native lost assignment draft');
  await page.evaluate(() => { window.__dropSaveAck = true; }); const assignmentBefore = patches();
  await click(page, '保存する'); await has(page, '保存の応答を確認できませんでした');
  assert.equal((await db.hrEvaluation.findUnique({ where: { id: e.id } })).evaluatorId, reviewer);
  await page.reload({ waitUntil: 'domcontentloaded' }); await has(page, '前回の保存結果が未確認');
  await click(page, '保存操作の結果を確認する'); await has(page, '前回の保存は完了しています');
  await click(page, '現在の保存内容を確認する');
  await page.waitForSelector('[aria-label="保存済みの上司担当者"]');
  assert.equal(await page.$eval('[aria-label="保存済みの上司担当者"]', field => field.textContent), 'Reviewer Synthetic');
  assert.equal(await page.$eval('[aria-label="保存済みの評価状態"]', field => field.textContent), '下書き');
  assert.ok(await page.evaluate(() => Object.keys(localStorage).some(k => k.startsWith('hr-evaluation-save-intent:'))));
  assert.equal(patches(), assignmentBefore + 1);
  await click(page, '入力を破棄し、保存内容で開き直す');
  await page.waitForFunction(() => !Object.keys(localStorage).some(k => k.startsWith('hr-evaluation-save-intent:')), { timeout: 12000 });
  assert.equal(await page.$eval('#evaluation-evaluator', field => field.value), reviewer);
  assert.equal(await page.$eval('textarea[placeholder^="この評価期間"]', field => field.value), 'Native lost assignment draft');
  assert.equal(patches(), assignmentBefore + 1);
  pass('Native lost assignment acknowledgment reload recovers exact evaluator and draft with no resave');

  await reset();
  await page.goto(origin + '/hr/evaluations/period/synthetic-period-A', { waitUntil: 'domcontentloaded' });
  await page.waitForSelector('#evaluation-creation-evaluator');
  await page.select('#evaluation-creation-evaluator', reviewer);
  await page.evaluate(() => { window.__dropCreationAck = true; });
  const creationBefore = http.filter(x => x.method === 'POST' && x.url === '/api/hr/evaluations').length;
  await page.evaluate(() => {
    const row = [...document.querySelectorAll('li')].find(item => item.querySelector('p')?.textContent.trim() === 'A Synthetic');
    const button = row && [...row.querySelectorAll('button')].find(button => button.textContent.trim() === '評価を作成');
    if (!button || button.disabled) throw Error('Missing active target creation row'); button.click();
  });
  await has(page, '評価の作成結果を確認できませんでした');
  const assigned = await db.hrEvaluation.findFirstOrThrow({ where: { periodId: 'synthetic-period-A', employeeId: 'synthetic-target-A' } });
  assert.equal(assigned.evaluatorId, reviewer);
  const metadata = await page.evaluate(() => JSON.parse(localStorage.getItem(Object.keys(localStorage).find(key => key.startsWith('hr-evaluation-create-intent:')))));
  assert.equal(metadata.version, 2); assert.equal(metadata.input.evaluatorId, reviewer);
  await page.reload({ waitUntil: 'domcontentloaded' }); await has(page, '前回の評価作成がまだ確認できていません');
  await click(page, '作成結果を確認する'); await has(page, '評価は保存済みです'); await click(page, '保存済みの評価を開く');
  await has(page, '評価詳細'); await page.waitForSelector('#evaluation-evaluator');
  assert.equal(await page.$eval('#evaluation-evaluator', field => field.value), reviewer);
  assert.equal(http.filter(x => x.method === 'POST' && x.url === '/api/hr/evaluations').length, creationBefore + 1);
  assert.equal(await page.evaluate(() => Object.keys(localStorage).some(key => key.startsWith('hr-evaluation-create-intent:'))), false);
  pass('Native assigned v2 creation loses acknowledgment then reloads and recovers exact reviewer without duplicate creation');
};
